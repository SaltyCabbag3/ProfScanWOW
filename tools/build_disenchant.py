"""Build ProfScan/DisenchantData.lua: the game's disenchant bands, and the gear
flagged as impossible to disenchant.

Usage:
    python build_disenchant.py [--build 1.60.1.70888] [--csv-dir DIR]

Reads the client's own tables (downloaded from wago.tools and cached in
tools/.db2cache/<build>/, like build_locks.py):
    ItemDisenchantLoot   the bands: quality x armor/weapon x item level range
    ItemSparse           quality, binding, flags (the "can't disenchant" flag)
    Item                 class (2 weapon, 4 armor)

The gear itself is not listed: about a third of the items have no ItemSparse
row in the downloadable tables (not shipped, or encrypted), so the Disenchant
scan finds gear by browsing the auction house instead. What a band
disenchants into is not in the client either (the server decides); those
yields are in Disenchant.lua.
"""
import argparse
import csv
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ADDON = HERE.parent
GAME = ADDON.parents[2]  # World of Warcraft/_forever_

NO_DISENCHANT = 0x8000  # ItemSparse Flags_0
TRADEABLE_BONDING = {0, 2, 3}  # none, bind on equip, bind on use (1 = pickup, 4 = quest)
CLASS_KEY = {2: "w", 4: "a"}


def game_build():
    info = GAME.parent / ".build.info"
    if not info.exists():
        return None
    lines = info.read_text(encoding="utf-8").splitlines()
    header = [h.split("!")[0] for h in lines[0].split("|")]
    for line in lines[1:]:
        row = dict(zip(header, line.split("|")))
        if row.get("Product") == "wowf":
            return row.get("Version")
    return None


def load(table, build, csv_dir):
    path = (Path(csv_dir) if csv_dir else HERE / ".db2cache" / build) / f"{table}.csv"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = f"https://wago.tools/db2/{table}/csv?build={build}"
        print("downloading", url)
        req = urllib.request.Request(url, headers={"User-Agent": "ProfScan-build-disenchant"})
        with urllib.request.urlopen(req, timeout=180) as resp:
            path.write_bytes(resp.read())
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build")
    ap.add_argument("--csv-dir")
    args = ap.parse_args()
    build = args.build or game_build()
    if not build:
        sys.exit("Could not read the game build; pass --build.")

    bands = sorted(
        (int(r["Quality"]), CLASS_KEY[int(r["Class"])], int(r["MinLevel"]), int(r["MaxLevel"]))
        for r in load("ItemDisenchantLoot", build, args.csv_dir)
        if int(r["Class"]) in CLASS_KEY and r["Subclass"] == "-1")
    classes = {int(r["ID"]): int(r["ClassID"]) for r in load("Item", build, args.csv_dir)}
    blocked = sorted(
        int(r["ID"]) for r in load("ItemSparse", build, args.csv_dir)
        if classes.get(int(r["ID"])) in CLASS_KEY and int(r["OverallQualityID"]) in (2, 3, 4)
        and int(r["Bonding"]) in TRADEABLE_BONDING and int(r["Flags_0"]) & NO_DISENCHANT)

    out = [
        f"-- Generated by tools/build_disenchant.py from the game's tables (build {build}).",
        "-- Do not edit by hand; run the script again instead.",
        "local _, ns = ...",
        "",
        "-- Disenchant bands as the game defines them (item level ranges):",
        "-- { quality = 2|3|4, kind = \"a\" (armor) | \"w\" (weapon), min =, max = }",
        "ns.DE_BANDS = {",
    ]
    for q, cls, lo, hi in bands:
        out.append(f"  {{ quality = {q}, kind = \"{cls}\", min = {lo}, max = {hi} }},")
    out.append("}")
    out.append("")
    out.append("-- Tradeable gear the game flags as impossible to disenchant.")
    out.append("ns.DE_BLOCKED = {")
    for i in range(0, len(blocked), 10):
        out.append("  " + " ".join(f"[{x}] = true," for x in blocked[i:i + 10]))
    out.append("}")
    target = ADDON / "DisenchantData.lua"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(bands)} bands, {len(blocked)} blocked items -> {target}")


if __name__ == "__main__":
    main()
