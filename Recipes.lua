local _, ns = ...

--[[
  Recipes

  Two sources, merged into ns.professions:
    RecipeData.lua   every Forever recipe from AtlasLoot's data (generated by
                     tools/build_recipes.py), plus gathering item lists
    your own profession windows: whenever one opens, the recipes the game
    shows are saved to ProfScanDB.captured (account wide). They correct
    AtlasLoot's reagents, add recipes it is missing, and the ones each
    character has learned are saved to ProfScanDB.known[character].

  ns.professions = { { name =, categories = { { name =, recipes = { recipe, ... } } } } }
  recipe = { spell =, item = crafted/gathered item ID or 0, skill =, name =,
             reagents = { { id, count }, ... },
             yieldMin, yieldMax = items made per craft, yieldSource = where that came from }

  Items per craft, in order of precedence:
    1. set by you (Recipe view or /pscan yield), ProfScanDB.yieldOverride
    2. the profession window, if the game reports a range
    3. AtlasLoot's number
  Margins use the middle of the range.
]]

ns.professions = {}
ns.recipeBySpell = {}
ns.recipesByItem = {} -- [crafted itemID] = { recipe, ... } (every recipe that makes it)
ns.recipesUsing = {} -- [reagent itemID] = { recipe, ... } (every recipe that uses it)

local CAPTURED_CATEGORY = "Seen in game"

local function CharKey()
  return UnitName("player") .. "-" .. GetRealmName()
end

local function Pairs(flat)
  local out = {}
  for i = 1, #flat, 2 do out[#out + 1] = { flat[i], flat[i + 1] } end
  return out
end

-- Rebuilds ns.professions from RecipeData.lua and the captured recipes.
function ns:BuildRecipes()
  wipe(self.professions)
  wipe(self.recipeBySpell)
  local byName = {}
  local function Profession(name)
    local p = byName[name]
    if not p then
      p = { name = name, categories = {} }
      byName[name] = p
      self.professions[#self.professions + 1] = p
    end
    return p
  end

  for _, prof in ipairs(self.RECIPE_DB or {}) do
    local p = Profession(prof.profession)
    for _, cat in ipairs(prof.categories) do
      local c = { name = cat.name, recipes = {} }
      for _, r in ipairs(cat.recipes or {}) do
        local recipe = { spell = r[1], item = r[2], skill = r[3], reagents = Pairs(r[4]),
                         yieldMin = r[5] or 1, yieldMax = r[5] or 1, yieldSource = "AtlasLoot", name = r[6],
                         profession = p.name, category = c.name }
        c.recipes[#c.recipes + 1] = recipe
        self.recipeBySpell[recipe.spell] = recipe
      end
      for _, id in ipairs(cat.items or {}) do
        c.recipes[#c.recipes + 1] = { spell = 0, item = id, skill = 0, reagents = {}, gathered = true,
                                      yieldMin = 1, yieldMax = 1, profession = p.name, category = c.name }
      end
      p.categories[#p.categories + 1] = c
    end
  end

  for profName, recipes in pairs(self.db.captured) do
    local p, extra = Profession(profName), nil
    for spell, cap in pairs(recipes) do
      local recipe = self.recipeBySpell[spell]
      if recipe then
        -- the game's own data wins over AtlasLoot's
        if cap.item ~= 0 then recipe.item = cap.item end
        if #cap.reagents > 0 then recipe.reagents = Pairs(cap.reagents) end
        if cap.yieldMin then
          recipe.yieldMin, recipe.yieldMax, recipe.yieldSource = cap.yieldMin, cap.yieldMax or cap.yieldMin, "game"
        end
        recipe.name = cap.name or recipe.name
      else
        if not extra then
          extra = { name = CAPTURED_CATEGORY, recipes = {} }
          p.categories[#p.categories + 1] = extra
        end
        recipe = { spell = spell, item = cap.item, skill = 0, reagents = Pairs(cap.reagents), name = cap.name,
                   yieldMin = cap.yieldMin or 1, yieldMax = cap.yieldMax or cap.yieldMin or 1,
                   yieldSource = cap.yieldMin and "game" or "unknown",
                   profession = p.name, category = CAPTURED_CATEGORY }
        extra.recipes[#extra.recipes + 1] = recipe
        self.recipeBySpell[spell] = recipe
      end
    end
  end

  table.sort(self.professions, function(a, b) return a.name < b.name end)
  for _, p in ipairs(self.professions) do
    for _, c in ipairs(p.categories) do
      for _, recipe in ipairs(c.recipes) do
        recipe.baseMin, recipe.baseMax, recipe.baseSource = recipe.yieldMin, recipe.yieldMax, recipe.yieldSource
      end
    end
  end
  self:ApplyYields()

  wipe(self.recipesByItem)
  wipe(self.recipesUsing)
  for _, recipe in pairs(self.recipeBySpell) do
    if recipe.item > 0 and #recipe.reagents > 0 then
      local makers = self.recipesByItem[recipe.item] or {}
      self.recipesByItem[recipe.item] = makers
      makers[#makers + 1] = recipe
    end
    for _, reagent in ipairs(recipe.reagents) do
      local users = self.recipesUsing[reagent[1]] or {}
      self.recipesUsing[reagent[1]] = users
      users[#users + 1] = recipe
    end
  end
  self:RebuildItems() -- the scan list comes from the recipes
  self:NotifyChanged()
end

-- Every item in a recipe's crafting tree: the product, its reagents, and for
-- each reagent that is itself crafted, the reagents of every recipe that
-- makes it, and so on down to raw materials. Conversions that loop (e.g.
-- lesser <-> greater essences) are followed once. Product first.
function ns:RecipeTreeItems(recipe)
  local ids, seen = {}, {}
  local VisitRecipe
  local function VisitItem(id)
    if seen[id] then return end
    seen[id] = true
    ids[#ids + 1] = id
    for _, maker in ipairs(self.recipesByItem[id] or {}) do
      if self:CanUseRecipe(maker) then VisitRecipe(maker) end -- only crafts you'd do (craft settings)
    end
  end
  VisitRecipe = function(r)
    for _, reagent in ipairs(r.reagents) do VisitItem(reagent[1]) end
  end
  if recipe.item > 0 then
    VisitItem(recipe.item)
  end
  VisitRecipe(recipe) -- enchants have no product; for the rest this is a no-op repeat
  return ids
end

-- Recomputes every recipe's yield from its base value and your overrides
-- (see the comment at the top).
function ns:ApplyYields()
  local override = self.db.yieldOverride
  for _, p in ipairs(self.professions) do
    for _, c in ipairs(p.categories) do
      for _, r in ipairs(c.recipes) do
        r.yieldMin, r.yieldMax, r.yieldSource = r.baseMin or 1, r.baseMax or 1, r.baseSource
        local o = r.spell > 0 and override[r.spell]
        if o then r.yieldMin, r.yieldMax, r.yieldSource = o[1], o[2], "set by you" end
      end
    end
  end
  self:NotifyChanged()
end

-- min/max = nil removes the override.
function ns:SetYieldOverride(spell, min, max)
  if min then
    max = math.max(min, max or min)
    self.db.yieldOverride[spell] = { min, max }
  else
    self.db.yieldOverride[spell] = nil
  end
  self:ApplyYields()
end

-- Prints what the profession API says about a recipe (for finding out why
-- yields are missing). Works best with that profession's window open.
function ns:PrintRecipeInfo(spell)
  if not spell then return self.Print("Usage: /pscan recipeinfo <spell ID>  (shift-click a recipe link)") end
  local recipe = self.recipeBySpell[spell]
  self.Print(("Recipe %d: %s"):format(spell, recipe and self:RecipeName(recipe) or "not in ProfScan's list"))
  if recipe then
    print(("  ProfScan uses %s per craft (%s)"):format(
      recipe.yieldMin == recipe.yieldMax and recipe.yieldMin or (recipe.yieldMin .. "-" .. recipe.yieldMax),
      recipe.yieldSource or "?"))
  end
  if not C_TradeSkillUI then return print("  C_TradeSkillUI does not exist") end
  local ok, schematic = pcall(C_TradeSkillUI.GetRecipeSchematic, spell, false)
  if not ok then
    print("  GetRecipeSchematic error: " .. tostring(schematic))
  elseif not schematic then
    print("  GetRecipeSchematic returned nothing (open the profession window?)")
  else
    print(("  schematic: outputItemID=%s quantityMin=%s quantityMax=%s"):format(
      tostring(schematic.outputItemID), tostring(schematic.quantityMin), tostring(schematic.quantityMax)))
    local keys = {}
    for k, v in pairs(schematic) do
      if type(v) ~= "table" then keys[#keys + 1] = k .. "=" .. tostring(v) end
    end
    table.sort(keys)
    print("  all fields: " .. table.concat(keys, ", "))
  end
  local timing = self:CraftTiming(recipe or { spell = spell, item = 0 })
  print(("  craft time: %s"):format(timing and ("%.2fs cast%s"):format(timing.cast,
    timing.cooldown and (", cooldown " .. ns.Duration(timing.cooldown)) or "") or "unknown"))
  if C_TradeSkillUI.GetRecipeNumItemsProduced then
    local okN, lo, hi = pcall(C_TradeSkillUI.GetRecipeNumItemsProduced, spell)
    print(("  GetRecipeNumItemsProduced: %s %s %s"):format(tostring(okN), tostring(lo), tostring(hi)))
  else
    print("  GetRecipeNumItemsProduced does not exist")
  end
end

-- Average number of items one craft makes.
function ns.Yield(recipe)
  return ((recipe.yieldMin or 1) + (recipe.yieldMax or recipe.yieldMin or 1)) / 2
end

-- "x2" or "x2-4" for recipes making more than one, else "".
function ns.YieldText(recipe)
  local lo, hi = recipe.yieldMin or 1, recipe.yieldMax or recipe.yieldMin or 1
  if hi <= 1 then return "" end
  return lo == hi and ("x%d"):format(lo) or ("x%d-%d"):format(lo, hi)
end

function ns:IsKnown(spell)
  local known = self.db.known[CharKey()]
  return known and known[spell] or false
end

-- Skill level of the current character in a profession, if a window was opened for it.
function ns:ProfessionSkill(profName)
  local skills = self.db.skills[CharKey()]
  return skills and skills[profName]
end

-- Crafting suggestions --------------------------------------------------------------------
-- Crafting trees, routes and "cheapest way" figures only use recipes you can
-- (or want to) craft: settings.craftUse[profession] = false leaves a profession
-- out, settings.craftKnownOnly keeps only recipes one of your characters has
-- learned. Left-out crafts are simply bought. The recipe you look at is
-- always shown; this only affects how its reagents are obtained.

function ns:KnownByAnyCharacter(spell)
  for _, known in pairs(self.db.known) do
    if known[spell] then return true end
  end
  return false
end

function ns:CanUseRecipe(recipe)
  if recipe.bundle then return true end
  local s = self.db.settings
  if recipe.profession and s.craftUse[recipe.profession] == false then return false end
  if s.craftKnownOnly and recipe.spell > 0 and not self:KnownByAnyCharacter(recipe.spell) then return false end
  return true
end

-- Professions any of your characters has (seen in their profession windows), plus this character's.
function ns:MyProfessions()
  local set = {}
  for _, skills in pairs(self.db.skills) do
    for prof in pairs(skills) do set[prof] = true end
  end
  for _, p in ipairs(self.professions) do
    if self:HasProfession(p.name) then set[p.name] = true end
  end
  return set
end

-- Does the current character have this profession? Asks the game's
-- profession list, falling back to what ProfScan saw in profession windows.
function ns:HasProfession(profName)
  if not profName then return false end
  if self:ProfessionSkill(profName) then return true end
  if GetProfessions and GetProfessionInfo then
    for _, index in ipairs({ GetProfessions() }) do
      if index and GetProfessionInfo(index) == profName then return true end
    end
  end
  return false
end

-- Opens the game's profession window at this recipe. Returns true if the call went through.
function ns:OpenRecipeInGame(recipe)
  if not (recipe and recipe.spell > 0 and C_TradeSkillUI and C_TradeSkillUI.OpenRecipe) then return false end
  local ok, err = pcall(C_TradeSkillUI.OpenRecipe, recipe.spell)
  if not ok then self.Print("Could not open the profession window: " .. tostring(err)) end
  return ok
end

function ns:RecipeName(recipe)
  if recipe.name then return recipe.name end
  if recipe.gathered then return (self:ItemName(recipe.item)) or ("item:" .. recipe.item) end
  local name = C_Spell and C_Spell.GetSpellName and C_Spell.GetSpellName(recipe.spell)
  return name or (GetSpellInfo and GetSpellInfo(recipe.spell)) or ("spell:" .. recipe.spell)
end

-- Capturing from the profession window -----------------------------------------------

local function ReadRecipe(recipeID)
  local info = C_TradeSkillUI.GetRecipeInfo(recipeID)
  local schematic = C_TradeSkillUI.GetRecipeSchematic(recipeID, false)
  if not (info and schematic) then return nil end
  local reagents = {}
  for _, slot in ipairs(schematic.reagentSlotSchematics or {}) do
    local reagent = slot.reagents and slot.reagents[1]
    -- optional and finishing slots don't count towards the cost
    if reagent and reagent.itemID and slot.required ~= false and (slot.quantityRequired or 0) > 0 then
      reagents[#reagents + 1] = reagent.itemID
      reagents[#reagents + 1] = slot.quantityRequired
    end
  end
  local made = { item = schematic.outputItemID or 0, name = info.name, reagents = reagents }
  -- items per craft: the schematic's range, or the older per-recipe call
  local lo, hi = schematic.quantityMin, schematic.quantityMax
  if not (lo and lo > 0) and C_TradeSkillUI.GetRecipeNumItemsProduced then
    lo, hi = C_TradeSkillUI.GetRecipeNumItemsProduced(recipeID)
  end
  if lo and lo > 0 then
    made.yieldMin = lo
    made.yieldMax = math.max(lo, hi or 0)
  end
  return made, info.learned
end

local reported = {} -- [profession] = "count/withYield/multi" last printed, so updates don't spam chat

function ns:CaptureTradeSkill()
  if not (C_TradeSkillUI and C_TradeSkillUI.GetAllRecipeIDs and C_TradeSkillUI.GetRecipeSchematic) then return end
  if C_TradeSkillUI.IsTradeSkillReady and not C_TradeSkillUI.IsTradeSkillReady() then return end
  local base = C_TradeSkillUI.GetBaseProfessionInfo and C_TradeSkillUI.GetBaseProfessionInfo()
  local profName = base and base.professionName
  if not profName or profName == "" then return end
  -- someone else's linked profession: their recipes are useful, their "learned" flags are not ours
  local mine = not (C_TradeSkillUI.IsTradeSkillLinked and C_TradeSkillUI.IsTradeSkillLinked())
    and not (C_TradeSkillUI.IsTradeSkillGuild and C_TradeSkillUI.IsTradeSkillGuild())

  local store = self.db.captured[profName] or {}
  self.db.captured[profName] = store
  local char = CharKey()
  local known = self.db.known[char] or {}
  self.db.known[char] = known

  local count, withYield, multi = 0, 0, 0
  for _, recipeID in ipairs(C_TradeSkillUI.GetAllRecipeIDs() or {}) do
    local ok, recipe, learned = pcall(ReadRecipe, recipeID)
    if ok and recipe then
      local old = store[recipeID]
      if not recipe.yieldMin and old and old.yieldMin then
        recipe.yieldMin, recipe.yieldMax = old.yieldMin, old.yieldMax -- keep a range read earlier
      end
      store[recipeID] = recipe
      count = count + 1
      if recipe.yieldMin then withYield = withYield + 1 end
      if (recipe.yieldMax or 1) > 1 then multi = multi + 1 end
      if mine then known[recipeID] = learned or nil end
    end
  end
  if mine and base.skillLevel then
    self.db.skills[char] = self.db.skills[char] or {}
    self.db.skills[char][profName] = base.skillLevel
  end
  if count > 0 then
    self:BuildRecipes()
    local summary = count .. "/" .. withYield .. "/" .. multi
    if reported[profName] ~= summary then
      reported[profName] = summary
      self.Print(("Read %d %s recipes; %d make more than one item%s."):format(count, profName, multi,
        withYield == 0 and " (the game gave no items-per-craft numbers, so the built-in ones are used)" or ""))
    end
  end
end

-- The list fills in over several updates; read it once things settle.
local pending, warned = false, false
local function ScheduleCapture()
  if pending then return end
  pending = true
  C_Timer.After(1, function()
    pending = false
    local ok, err = pcall(ns.CaptureTradeSkill, ns)
    if not ok and not warned then
      warned = true
      ns.Print("Could not read the profession window (" .. tostring(err) .. "). The recipe list still works from built-in data.")
    end
  end)
end
ns.TRADE_SKILL_SHOW = ScheduleCapture
ns.TRADE_SKILL_LIST_UPDATE = ScheduleCapture
ns:RegisterEvent("TRADE_SKILL_SHOW")
ns:RegisterEvent("TRADE_SKILL_LIST_UPDATE")
